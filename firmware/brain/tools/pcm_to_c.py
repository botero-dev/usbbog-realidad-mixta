#!/usr/bin/env python3
"""Convert a raw 16-bit mono PCM file into a C++ array the firmware can play.

WHY AN ARRAY AND NOT THE LINKER'S BINARY-EMBED SYMBOLS
------------------------------------------------------
PlatformIO's `board_build.embed_files` works (the Arduino builder pipes
`_embed_files.py` through objcopy), but objcopy derives its symbols from the path
it is handed, which is the ABSOLUTE path. So the symbol for
`.../firmware/brain/audio/clip.pcm` becomes
`_binary__home_abotero_abotero_usbbog_realidad_mixta_firmware_brain_audio_clip_pcm_start`
-- a name that changes the moment the project is moved or cloned elsewhere, and
that is unpleasant to reference from C.

An array has no such problem and needs no linker knowledge.

CONVERTING THE SOURCE AUDIO
---------------------------
The firmware's I2S port is configured for 16-bit stereo at 44.1 kHz, and this
script emits mono 16-bit at that same rate, so the only work at playback time is
duplicating each sample into both slots. Convert with:

    ffmpeg -i INPUT.wav -ac 1 -ar 44100 -sample_fmt s16 -f s16le audio/clip.pcm

A mismatch (wrong rate, wrong channel count) is SILENT -- it just plays at the
wrong speed or with wrong pitch. Nothing checks it at runtime.

USAGE
-----
    python3 tools/pcm_to_c.py audio/clip.pcm

Writes include/audio_clip.h and src/audio_clip.cpp, relative to the project root
(two levels up from this script).
"""

import os
import struct
import sys

PER_LINE = 16


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2

    here = os.path.dirname(os.path.abspath(__file__))
    project = os.path.dirname(here)          # firmware/brain
    pcm_path = sys.argv[1]
    if not os.path.isabs(pcm_path):
        pcm_path = os.path.join(project, pcm_path)

    if not os.path.isfile(pcm_path):
        print("no such file: %s" % pcm_path)
        return 1

    with open(pcm_path, "rb") as fh:
        raw = fh.read()
    if len(raw) % 2:
        print("warning: %d bytes is not a whole number of 16-bit samples" % len(raw))
        raw = raw[: len(raw) & ~1]

    samples = struct.unpack("<%dh" % (len(raw) // 2), raw)
    count = len(samples)
    seconds = count / 44100.0
    base = os.path.splitext(os.path.basename(pcm_path))[0]

    header = os.path.join(project, "include", "audio_clip.h")
    source = os.path.join(project, "src", "audio_clip.cpp")

    # `include/` may not exist yet -- a project that has only ever had a src/
    # directory does not get one for free.
    os.makedirs(os.path.dirname(header), exist_ok=True)

    with open(header, "w") as fh:
        fh.write(
            "// audio_clip.h -- GENERATED by tools/pcm_to_c.py from %s. Do not edit.\n"
            "//\n"
            "// %d samples of signed 16-bit little-endian PCM, MONO, 44100 Hz\n"
            "// (%.3f s). Convert the source audio with:\n"
            "//   ffmpeg -i INPUT.wav -ac 1 -ar 44100 -sample_fmt s16 -f s16le %s\n"
            "#pragma once\n"
            "\n"
            "#include <stdint.h>\n"
            "\n"
            "constexpr unsigned CLIP_SAMPLES = %du;\n"
            "\n"
            "extern const int16_t clip_pcm[CLIP_SAMPLES];\n"
            % (os.path.basename(pcm_path), count, seconds, os.path.basename(pcm_path),
               count)
        )

    with open(source, "w") as fh:
        fh.write('// GENERATED by tools/pcm_to_c.py -- do not edit, edit the .pcm instead.\n')
        fh.write('#include "audio_clip.h"\n\n')
        fh.write("const int16_t clip_pcm[CLIP_SAMPLES] = {\n")
        for i in range(0, count, PER_LINE):
            chunk = samples[i : i + PER_LINE]
            fh.write("    " + ", ".join("%6d" % s for s in chunk) + ",\n")
        fh.write("};\n")

    print("read      %s" % pcm_path)
    print("wrote     %s" % os.path.relpath(header, project))
    print("wrote     %s" % os.path.relpath(source, project))
    print("samples   %d  (%.3f s at 44100 Hz, mono 16-bit)" % (count, seconds))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
